export function normalizeName(value) {
  return String(value || '')
    .trim()
    .toLowerCase()
    .replace(/\+/g, '+')
    .replace(/\s+/g, ' ');
}

export function normalizeUrl(value) {
  const trimmed = String(value || '').trim();
  if (!trimmed) return '';
  if (/^https?:\/\//i.test(trimmed)) return trimmed;
  return `https://${trimmed}`;
}

export function lookupCancelUrl(serviceName) {
  const key = normalizeName(serviceName);
  if (!key) return null;
  if (CANCEL_LINKS[key]) return CANCEL_LINKS[key];

  const alias = ALIASES[key];
  if (alias && CANCEL_LINKS[alias]) return CANCEL_LINKS[alias];

  // Fuzzy search - jos kirjoitettu melkein oikein tai sisältää sanan
  for (const [name, url] of Object.entries(CANCEL_LINKS)) {
    if (key === name) return url;
    if (key.startsWith(`${name} `) || name.startsWith(`${key} `)) return url;
  }

  return null;
}

export function getCancelUrl(serviceName, customUrl) {
  const custom = normalizeUrl(customUrl);
  if (custom) return custom;

  return (
    lookupCancelUrl(serviceName) ||
    `https://www.google.com/search?q=${encodeURIComponent(`${serviceName} cancel subscription`)}`
  );
}